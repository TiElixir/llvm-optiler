"""Generate ``frontend/src/api/types.ts`` from the pydantic models in ``backend/schemas.py``.

    python scripts/gen_types.py           # write the file
    python scripts/gen_types.py --check   # exit 1 if the file on disk is stale

No dependencies beyond pydantic: the models' JSON schemas are converted to TypeScript here.
Response models are emitted with every field present (the API serialises defaults); request
models keep their defaulted fields optional.
"""
from __future__ import annotations

import sys
import typing
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from pydantic.json_schema import models_json_schema  # noqa: E402

from backend import schemas  # noqa: E402

OUT = ROOT / "frontend" / "src" / "api" / "types.ts"

# Literal aliases exported by name; an inline enum with exactly these values is replaced by the alias.
ALIASES = ["StageId", "RunStatus", "Attribution", "Phase"]
RESPONSE_MODELS = [
    "Snapshot", "Stage", "Timing", "Metrics", "Impact", "Finding", "PipelinePatchOp", "Fix", "Op",
    "Link", "StageOps", "FxNode", "RunSettings", "Run", "RunSummary", "CreateRunResponse",
    "ProgressEvent", "SnapshotText", "DiffResult", "TemplateInfo", "TemplateSource",
]
REQUEST_MODELS = ["CreateRunRequest"]

HEADER = """\
// GENERATED by scripts/gen_types.py from backend/schemas.py. DO NOT EDIT BY HAND.
// Regenerate with `python scripts/gen_types.py`; `--check` fails when this file is stale.
"""
EXTRA = "export type ToolchainReport = Record<string, unknown>;\n"


class Converter:
    def __init__(self) -> None:
        self.alias_by_values = {
            tuple(typing.get_args(getattr(schemas, n))): n for n in ALIASES}

    def ts(self, s: dict[str, Any] | bool) -> str:
        if s is True or s == {}:
            return "unknown"
        if s is False:
            return "never"
        if "$ref" in s:
            return s["$ref"].rsplit("/", 1)[-1]
        if "allOf" in s and len(s["allOf"]) == 1:
            return self.ts(s["allOf"][0])
        if "anyOf" in s or "oneOf" in s:
            parts = [self.ts(x) for x in s.get("anyOf") or s["oneOf"]]
            return self.union(parts)
        if "const" in s:
            return self.literal(s["const"])
        if "enum" in s:
            alias = self.alias_by_values.get(tuple(s["enum"]))
            return alias or self.union([self.literal(v) for v in s["enum"]])
        t = s.get("type")
        if isinstance(t, list):
            return self.union([self.ts({**s, "type": x}) for x in t])
        if t == "string":
            return "string"
        if t in ("number", "integer"):
            return "number"
        if t == "boolean":
            return "boolean"
        if t == "null":
            return "null"
        if t == "array":
            if "prefixItems" in s:
                return "[" + ", ".join(self.ts(x) for x in s["prefixItems"]) + "]"
            inner = self.ts(s.get("items", {}))
            return f"({inner})[]" if "|" in inner else f"{inner}[]"
        if t == "object" or "properties" in s or "additionalProperties" in s:
            if s.get("properties"):
                raise ValueError("inline object with properties; give the model a name")
            ap = s.get("additionalProperties", True)
            return f"Record<string, {self.ts(ap)}>"
        raise ValueError(f"unsupported schema: {s}")

    @staticmethod
    def literal(v: Any) -> str:
        if isinstance(v, bool):
            return "true" if v else "false"
        if v is None:
            return "null"
        if isinstance(v, str):
            return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
        return str(v)

    @staticmethod
    def union(parts: list[str]) -> str:
        seen: list[str] = []
        for p in sorted(parts, key=lambda p: p == "null"):  # null last, otherwise schema order
            if p not in seen:
                seen.append(p)
        return " | ".join(seen)

    def declaration(self, name: str, s: dict[str, Any], is_request: bool) -> str:
        if s.get("type") == "object" and "properties" in s:
            required = set(s.get("required", []))
            lines = [f"export interface {name} {{"]
            for key, prop in s["properties"].items():
                optional = is_request and key not in required
                lines.append(f"  {key if key.isidentifier() else self.literal(key)}"
                             f"{'?' if optional else ''}: {self.ts(prop)};")
            lines.append("}")
            return "\n".join(lines)
        return f"export type {name} = {self.ts(s)};"


def generate() -> str:
    names = RESPONSE_MODELS + REQUEST_MODELS
    models = [(getattr(schemas, n), m) for n, m in
              [(n, "serialization") for n in RESPONSE_MODELS] + [(n, "validation") for n in REQUEST_MODELS]]
    _, defs = models_json_schema(models, by_alias=True, ref_template="#/$defs/{model}")
    defs = defs.get("$defs", {})
    missing = [n for n in names if n not in defs]
    extra = sorted(set(defs) - set(names))
    if missing or extra:
        raise SystemExit(f"gen_types: model lists out of sync with schemas (missing {missing}, unlisted {extra})")

    conv = Converter()
    out = [HEADER]
    for n in ALIASES:
        vals = typing.get_args(getattr(schemas, n))
        out.append(f"export type {n} = {conv.union([conv.literal(v) for v in vals])};\n")
    for n in names:
        out.append(conv.declaration(n, defs[n], n in REQUEST_MODELS) + "\n")
    out.append(EXTRA)
    return "\n".join(out)


def check() -> bool:
    return OUT.exists() and OUT.read_text() == generate()


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if "--check" in argv:
        if check():
            print(f"{OUT.relative_to(ROOT)} is up to date")
            return 0
        print(f"{OUT.relative_to(ROOT)} is stale or missing; run `python scripts/gen_types.py`")
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(generate())
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
